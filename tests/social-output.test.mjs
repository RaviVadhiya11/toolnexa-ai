import test from 'node:test';
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import ts from 'typescript';

// Exercise the actual TypeScript formatter in Node (no browser or API required).
const source=readFileSync(new URL('../lib/social-output.ts',import.meta.url),'utf8');
const compiled=ts.transpileModule(source,{compilerOptions:{
 target:ts.ScriptTarget.ES2022,module:ts.ModuleKind.ESNext
}}).outputText;
const {parseSocialOutput}=await import('data:text/javascript;base64,'+Buffer.from(compiled).toString('base64'));

test('Gemini result splits into individually copyable titles, hashtags, caption and description',()=>{
 const input='GENERATED BY GEMINI AI\n\nTITLES\n'+
  '1. How to Create Engaging Educational Videos\n'+
  '2. Step-by-Step Guide to Video Production\n\nHASHTAGS\n'+
  '#EducationalVideos #ContentCreation #TeachingTips\n\n'+
  'CAPTION\nLearn how to create clear educational videos.\n\n'+
  'DESCRIPTION\nPlan your lesson, record a video and review the audio.\n\n'+
  'Tip: Review every suggestion for accuracy before publishing.';
 const parsed=parseSocialOutput(input);
 assert.equal(parsed?.source,'gemini');
 assert.deepEqual(parsed?.titles,[
  'How to Create Engaging Educational Videos',
  'Step-by-Step Guide to Video Production'
 ]);
 assert.deepEqual(parsed?.hashtags,['#EducationalVideos','#ContentCreation','#TeachingTips']);
 assert.equal(parsed?.caption,'Learn how to create clear educational videos.');
 assert.equal(parsed?.description,'Plan your lesson, record a video and review the audio.');
 assert.match(parsed?.tip||'',/Review every suggestion/);
});

test('offline suggestions also split without asking an AI model to regenerate',()=>{
 const input='SMART OFFLINE SUGGESTIONS (not generated by an AI model)\n\n'+
  'TITLES\n1. A practical guide to gardening\n2. 5 garden ideas\n\n'+
  'HASHTAGS\n#gardening #tips #plants\n\nTIP\nReview relevance before posting.';
 const parsed=parseSocialOutput(input);
 assert.equal(parsed?.source,'offline');
 assert.deepEqual(parsed?.titles,['A practical guide to gardening','5 garden ideas']);
 assert.deepEqual(parsed?.hashtags,['#gardening','#tips','#plants']);
 assert.equal(parsed?.caption,'');
 assert.equal(parsed?.description,'');
 assert.equal(parsed?.tip,'Review relevance before posting.');
});

test('non-creator output is never parsed as social suggestions',()=>{
 assert.equal(parseSocialOutput('This is a standard JSON formatter result.'),null);
 assert.equal(parseSocialOutput('GENERATED BY GEMINI AI\n\nTITLES\n\nHASHTAGS\n'),null);
});

test('creator UI offers per-item copy and retains full-result download',()=>{
 const ui=readFileSync(new URL('../components/advanced-tool-runner.tsx',import.meta.url),'utf8');
 for(const label of ['Copy all titles','Copy title ','Copy all hashtags','Copy hashtag ','Copy caption','Copy description','Copy full result','Download text'])
  assert.ok(ui.includes(label),'Missing creator copy action: '+label);
 assert.match(ui,/navigator\.clipboard\.writeText\(value\)/);
 assert.match(ui,/parseSocialOutput\(result\)/);
 assert.match(ui,/aria-live="polite"/);
});
