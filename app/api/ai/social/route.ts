import {NextRequest,NextResponse} from 'next/server';
import {serverSupabase} from '@/lib/supabase/server';
import {adminDb} from '@/lib/admin';

export const runtime='nodejs';
const noStore={'Cache-Control':'no-store'};
const reply=(data:object,status=200)=>NextResponse.json(data,{status,headers:noStore});
const permittedModels=new Set(['gemini-3.5-flash-lite','gemini-3.1-flash-lite']);
const platforms=new Set(['YouTube','Instagram','TikTok','LinkedIn']);
type SocialDraft={titles:string[];hashtags:string[];caption:string;description:string};

function renderDraft(draft:SocialDraft):string{
 const titles=draft.titles.filter(s=>typeof s==='string').slice(0,6).map(x=>x.slice(0,145));
 const hashtags=draft.hashtags.filter(s=>typeof s==='string').slice(0,16).map(x=>x.replace(/\s+/g,'').slice(0,60));
 if(!titles.length||!hashtags.length)throw new Error('Invalid model response');
 return 'GENERATED BY GEMINI AI\n\nTITLES\n'+titles.map((v,i)=>String(i+1)+'. '+v).join('\n')+
  '\n\nHASHTAGS\n'+hashtags.join(' ')+
  '\n\nCAPTION\n'+draft.caption.slice(0,1200)+
  '\n\nDESCRIPTION\n'+draft.description.slice(0,1500)+
  '\n\nTip: Review every suggestion for accuracy before publishing.';
}
export async function POST(request:NextRequest){
 try{
  if(process.env.GEMINI_AI_ENABLED!=='true'||!process.env.GEMINI_API_KEY)
   return reply({error:'Gemini AI is not configured yet. Choose Offline Smart Mode instead.'},503);
  if(request.headers.get('origin')!==request.nextUrl.origin)
   return reply({error:'Invalid request origin'},403);
  if(!(request.headers.get('content-type')||'').startsWith('application/json'))
   return reply({error:'Expected JSON request'},415);
  const size=Number(request.headers.get('content-length')||'0');
  if(size>4000)return reply({error:'Request is too large'},413);
  const supabase=await serverSupabase();
  if(!supabase)return reply({error:'Sign in service unavailable'},503);
  const {data:{user},error:authError}=await supabase.auth.getUser();
  if(authError||!user)return reply({error:'Sign in to generate with Gemini AI, or use Offline Smart Mode.'},401);
  let body:unknown;
  try{body=await request.json()}catch{return reply({error:'Invalid JSON'},400)}
  const b=(body&&typeof body==='object')?body as {topic?:unknown;platform?:unknown}:null;
  const topic=typeof b?.topic==='string'?b.topic.trim():'';
  const platform=typeof b?.platform==='string'?b.platform:'';
  if(topic.length<3||topic.length>300||!platforms.has(platform))
   return reply({error:'Provide a 3–300 character topic and supported platform.'},400);

  const db=adminDb();
  if(!db)return reply({error:'AI usage protection is unavailable'},503);
  // Atomic, server-only limits: 3 signed-in requests/day and max 30/day globally.
  const {data:used,error:quotaError}=await db.rpc('reserve_social_ai_usage',{p_user_id:user.id});
  if(quotaError){
   if(quotaError.code==='P0001')
    return reply({error:'Free Gemini AI usage allowance reached. Try tomorrow or use Offline Smart Mode.'},429);
   return reply({error:'AI daily limit verification unavailable'},503);
  }
  if(typeof used!=='number'||used<1||used>3)return reply({error:'Unexpected AI usage state'},503);
  const modelName=process.env.GEMINI_MODEL||'gemini-3.5-flash-lite';
  if(!permittedModels.has(modelName))return reply({error:'Selected AI model is not approved for this tool'},503);

  const controller=new AbortController();
  const timeout=setTimeout(()=>controller.abort(),20000);
  let response:Response;
  try{
   response=await fetch('https://generativelanguage.googleapis.com/v1beta/models/'+modelName+':generateContent',{
    method:'POST',cache:'no-store',signal:controller.signal,
    headers:{'x-goog-api-key':process.env.GEMINI_API_KEY,'Content-Type':'application/json'},
    body:JSON.stringify({
     systemInstruction:{parts:[{text:'You are a helpful social media writing assistant. Create accurate, non-deceptive, specific drafts. Never assert facts about a product that were not provided. Return JSON only as requested.'}]},
     contents:[{role:'user',parts:[{text:'Platform: '+platform+'\nTopic: '+topic+'\nProvide six distinct engaging titles, 12-16 relevant hashtags (starting with #), one concise caption and one short description. No clickbait, no invented facts.'}]}],
     generationConfig:{temperature:0.75,maxOutputTokens:1200,responseMimeType:'application/json'}
    })
   });
  }finally{clearTimeout(timeout)}
  if(response.status===429)return reply({error:'Google Gemini Free Tier limit reached. Try later or switch to Offline Smart Mode.'},429);
  if(!response.ok)return reply({error:'Gemini AI cannot process this request right now. Try Offline Smart Mode.'},502);
  const parsed=await response.json() as {candidates?:Array<{content?:{parts?:Array<{text?:string}>}} >};
  const raw=parsed.candidates?.[0]?.content?.parts?.map(p=>p.text||'').join('')||'';
  if(raw.length>15000||raw.length<2)return reply({error:'Gemini returned an unexpected result. Please try again.'},502);
  let data:unknown;
  try{data=JSON.parse(raw)}catch{return reply({error:'Gemini response could not be formatted; retry or use Offline Smart Mode.'},502)}
  if(!data||typeof data!=='object')return reply({error:'Unexpected AI response'},502);
  const draft=data as Partial<SocialDraft>;
  if(!Array.isArray(draft.titles)||!Array.isArray(draft.hashtags)||
     typeof draft.caption!=='string'||typeof draft.description!=='string'||
     draft.titles.some(x=>typeof x!=='string')||draft.hashtags.some(x=>typeof x!=='string'))
   return reply({error:'Gemini returned an incomplete result'},502);
  return reply({text:renderDraft(draft as SocialDraft),model:modelName,used,limit:3});
 }catch(error){
  if(error instanceof Error&&error.name==='AbortError')
   return reply({error:'Gemini took too long. Try again or use Offline Smart Mode.'},504);
  return reply({error:'Gemini AI temporarily unavailable. Use Offline Smart Mode.'},503);
 }
}
