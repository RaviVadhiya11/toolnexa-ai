/**
 * Extract the fixed section headings emitted by the Gemini and Offline Social
 * Generator. This is presentation-only: never use it to approve an AI request.
 * Keep the original raw text for "Copy full result" and text downloads.
 */
export type SocialOutput={
 source:'gemini'|'offline';
 titles:string[];
 hashtags:string[];
 caption:string;
 description:string;
 tip:string;
};
type Heading='TITLES'|'HASHTAGS'|'CAPTION'|'DESCRIPTION'|'TIP';
const headings=new Set<Heading>(['TITLES','HASHTAGS','CAPTION','DESCRIPTION','TIP']);

export function parseSocialOutput(value:string):SocialOutput|null{
 const source=value.startsWith('GENERATED BY GEMINI AI')?'gemini':
  value.startsWith('SMART OFFLINE SUGGESTIONS (not generated by an AI model)')?'offline':null;
 if(!source)return null;
 const sections:Partial<Record<Heading,string[]>>={};
 let current:Heading|null=null,inlineTip='';
 for(const rawLine of value.replace(/\r\n?/g,'\n').split('\n')){
  const trimmed=rawLine.trim();
  const candidate=trimmed.toUpperCase() as Heading;
  if(headings.has(candidate)){
   current=candidate;
   sections[current]=[];
  }else if(/^Tip:\s*/i.test(trimmed)){
   inlineTip=trimmed.replace(/^Tip:\s*/i,'');
   current=null;
  }else if(current){
   sections[current]?.push(rawLine);
  }
 }
 const titles=(sections.TITLES??[]).map(line=>line.replace(/^\s*\d{1,2}[.)]\s*/u,'').trim())
  .filter(Boolean).slice(0,6);
 const hashtags=(sections.HASHTAGS??[]).join(' ').split(/\s+/u)
  .filter(tag=>tag.startsWith('#')&&tag.length>1).slice(0,16);
 if(!titles.length||!hashtags.length)return null;
 return {
  source,titles,hashtags,
  caption:(sections.CAPTION??[]).join('\n').trim(),
  description:(sections.DESCRIPTION??[]).join('\n').trim(),
  tip:inlineTip||(sections.TIP??[]).join('\n').trim()
 };
}
